# Read and import the demo source project of test/fixtures/mirror_demo, without Redmine.

require "minitest/autorun"
require "erb"
require_relative "../lib/redmine_mirror"
require_relative "mirror_demo_source"

class MirrorDemoTest < Minitest::Test
  def setup
    @source = MirrorDemoSource.new
    @project_id = @source.project_id
  end

  # The demo source has no Project Enumerations plugin and no repository: those modules stay unselected.
  MODULES = RedmineMirror::REGISTRY.keys - %w[project_enumerations repositories]

  def catalog
    @catalog ||= RedmineMirror::SourceCatalog.new(client: @source, project_id: @project_id,
      adapters: RedmineMirror::REGISTRY.resolve(MODULES)).fetch
  end

  def test_the_catalog_reads_every_module_of_the_demo_project
    statistics = catalog.fetch("module_statistics").transform_values { |counts| counts.fetch("records") }
    assert_equal({ "issue_tracking" => 53, "time_tracking" => 132, "issue_journals" => 141, "issue_attachments" => 23,
      "issue_relations" => 6, "issue_categories" => 4, "project_versions" => 4, "project_members" => 6, "wiki" => 12,
      "documents" => 5, "project_files" => 4, "news" => 4, "issue_tags" => 53, "agile_sprints" => 5,
      "agile_issues" => 53, "project_queries" => 11 }, statistics.slice(*%w[issue_tracking time_tracking issue_journals
        issue_attachments issue_relations issue_categories project_versions project_members wiki documents project_files
        news issue_tags agile_sprints agile_issues project_queries]))
    assert_equal 4, catalog.dig("module_statistics", "issue_hierarchy", "with_parent")
    assert_equal 8, catalog.dig("module_statistics", "issue_tags", "tags")
    # Every request the catalog made was recorded: the fixtures are complete.
    assert_empty @source.unrecorded
  end

  def test_the_catalog_keeps_the_source_refusals_and_text_formats
    # The source keeps its users' details to itself (Mirror source: not_shared).
    assert_equal "not_shared", catalog.fetch("user_details_refusal")
    assert_equal ["Alice Client", "Bob Former", "John Doe", "Mirror Reader", "Paula Pilot", "Tom Developer"], catalog.fetch("user").values.sort
    # Redmine's default references, plus two values to map in each list.
    assert_equal %w[Bug Feature Support Task Epic], catalog.fetch("tracker").values
    assert_equal ["New", "In Progress", "Resolved", "Feedback", "Closed", "Rejected", "In review", "On hold"], catalog.fetch("status").values
    assert_equal ["Design", "Development", "Testing", "Project management"], catalog.fetch("activity").values
    # Custom fields are read from the issues: the reader account may not list them.
    assert_equal ["Severity", "Customer reference"], catalog.fetch("custom_field").values
    assert_equal({ "textile" => 20, "markdown" => 2, "plain" => 184 }, catalog.fetch("text_formats"))
  end

  def test_the_replay_answers_like_the_source
    assert_equal "mirror-demo", @source.get("projects/#{@project_id}.json").dig("project", "identifier")
    error = assert_raises(RedmineMirror::Error) { @source.get("projects/#{@project_id}/issue_categories.json") }
    assert_match(/HTTP 403/, error.message)
    error = assert_raises(RedmineMirror::Error) { @source.get("custom_fields.json") }
    assert_match(/HTTP 403/, error.message)
    issue = RedmineMirror::Adapters::Issues.new.records(@source, @project_id).first
    assert_equal issue.fetch("id"), @source.get("issues/#{issue.fetch('id')}.json", "include" => "journals").dig("issue", "id")
    # Files over 100 KB are declared by size; their generated bytes have that size.
    large = MirrorDemoSource.files.find { |_, file| file["size"] }
    assert_equal large.last.fetch("size"), @source.download_attachment(0, path: large.first).bytesize
    assert_raises(RedmineMirror::Error) { @source.download_attachment(0, max_bytes: 1024, path: large.first) }
    assert_raises(RedmineMirror::Error) { @source.get("issues/999999.json") }
  end

  # Every issue and time entry converts into its destination write: Redmine 4 dates,
  # Textile, private issues, versions, and a locked author anonymized for time entries.
  def test_every_issue_and_time_entry_builds_its_destination_write
    mappings = %w[tracker status priority activity user].to_h { |kind| [kind, catalog.fetch(kind).keys.to_h { |id| [id, "1"] }] }
    lookup = ->(_key, id) { id + 100_000 }
    issues = RedmineMirror::Adapters::Issues.new(users: RedmineMirror::Adapters::Users.new)
    payloads = issues.records(@source, @project_id).map { |record| issues.payload(record, 1, mappings, lookup) }
    assert_equal 53, payloads.size
    assert(payloads.all? { |payload| payload["created_on"].to_s.end_with?("Z") && payload["tracker_id"] == 1 })
    assert_equal 8, payloads.count { |payload| payload["fixed_version_id"] }
    assert_equal 1, payloads.count { |payload| payload["is_private"] }
    # Each issue is one case, named in its subject.
    themes = payloads.map { |payload| payload.fetch("subject")[/\A\[(\w+)\]/, 1] }.tally
    assert_equal({ "Text" => 11, "Files" => 5, "State" => 15, "History" => 5, "Tree" => 6, "Links" => 3, "Watch" => 1, "Time" => 3,
      "Agile" => 4 }, themes)

    times = RedmineMirror::Adapters::TimeEntries.new(users: RedmineMirror::Adapters::Users.new)
    mappings["user"][catalog.fetch("user").key("Bob Former")] = "anonymous"
    entries = times.records(@source, @project_id).map do |record|
      times.payload(record, 1, mappings, lookup, options: { "anonymous_user_id" => 5 })
    end
    assert_equal 132, entries.size
    assert_includes entries.map { |entry| entry.fetch("user_id") }, 5
    assert_empty @source.unrecorded
  end

  private

  def summary(events)
    events.group_by { |event| event.fetch(:module) }.transform_values { |list| list.map { |event| event.fetch(:action) }.tally }
  end
end
